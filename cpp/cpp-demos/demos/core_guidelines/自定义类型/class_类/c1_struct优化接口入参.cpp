/*
================================================================================
C++ Core Guidelines — C.1

将相关数据组织到结构体或类中

--------------------------------------------------------------------------------
原则说明：

    如果若干数据在概念上属于同一个实体，
    就应当在代码中用 struct 或 class 表达这种关系。

--------------------------------------------------------------------------------
原因：

    1. 提高可理解性
       相关数据被清晰归类，代码语义更明确。

    2. 防止参数顺序错误
       多个同类型参数容易写错顺序。

    3. 体现“概念模型”
       如果数据在现实世界中是一个整体，
       那么代码中也应当表达这种整体性。

--------------------------------------------------------------------------------
核心思想：

    代码结构应反映真实概念结构。
================================================================================
*/

#include <iostream>

// ❌ Bad: 裸参数，语义不清晰
void draw_bad(double x, double y, double z) {
    std::cout << "Drawing at (" << x << ", "
              << y << ", "
              << z << ")\n";
}

// ✅ Good: 使用结构体表达概念
struct Point {
    double x;
    double y;
    double z;
};

void draw_good(Point p) {
    std::cout << "Drawing at (" << p.x << ", "
              << p.y << ", "
              << p.z << ")\n";
}

int main() {

    std::cout << "===== Bad 示例 =====\n";

    // 问题：参数顺序容易写错
    draw_bad(1.0, 2.0, 3.0);      // 正确
    draw_bad(3.0, 1.0, 2.0);      // 编译通过，但语义错误


    std::cout << "\n===== Good 示例 =====\n";

    Point p{1.0, 2.0, 3.0};
    draw_good(p);

    // 即使赋值时顺序改变，语义仍然清晰
    Point q;
    q.x = 3.0;
    q.y = 1.0;
    q.z = 2.0;
    draw_good(q);

    return 0;
}
