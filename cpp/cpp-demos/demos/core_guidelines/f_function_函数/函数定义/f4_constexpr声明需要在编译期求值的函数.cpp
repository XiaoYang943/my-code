/*
================================================================================
C++ Core Guidelines — F.4

如果一个函数可能需要在编译期求值，应声明为 constexpr

--------------------------------------------------------------------------------
原则说明：

    constexpr 是对编译器的一种声明：
        “该函数满足常量表达式规则，可以在编译期执行。”

    它不是强制在编译期执行，
    而是赋予函数“具备编译期求值能力”。

--------------------------------------------------------------------------------
原因：

    只有声明为 constexpr，
    编译器才允许该函数在常量表达式上下文中被编译期求值。

--------------------------------------------------------------------------------
工程级理解：

    constexpr = 允许在编译期执行的纯计算函数

    如果函数：
        - 不依赖运行期状态
        - 不涉及 IO
        - 不修改外部状态
        - 只做纯计算

    那么应考虑声明为 constexpr。

--------------------------------------------------------------------------------
编译期执行的好处：

    1. 性能更优
       编译期完成计算，运行期无需重复计算

    2. 错误前移
       若用于常量表达式，错误会在编译阶段暴露

    3. 语义更明确
       constexpr 函数通常是纯函数（无副作用），
       逻辑更稳定，可推理性更强

--------------------------------------------------------------------------------
注意：

    不要滥用 constexpr。

    适合 constexpr 的场景：
        - 数学函数
        - 纯算法
        - 常量计算

    不适合 constexpr 的场景：
        - IO 操作
        - 依赖外部状态
        - 业务流程逻辑
        - 配置加载

--------------------------------------------------------------------------------
核心思想：

    如果一个函数“可能需要”在编译期执行，
    就应该声明 constexpr。

================================================================================
*/


// 欧几里得算法：计算最大公约数
constexpr int gcd(int a, int b) {
    while (b != 0) {
        int t = b;
        b = a % b;
        a = t;
    }
    return a;
}


int main() {

    // ✅ 编译期执行
    // 因为 i 被要求是常量表达式
    constexpr int i = gcd(11, 121);

    // ❗ 运行期执行
    // 因为参数不是编译期常量
    int a = 11;
    int b = 121;
    int j = gcd(a, b);
}
