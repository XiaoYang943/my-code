#include <iostream>

/*
================================================================================
C++ Core Guidelines — SF.3

所有被多个源文件使用的声明，应放在头文件中

--------------------------------------------------------------------------------
原则说明：

    如果一个函数、类、变量会被多个源文件使用，
    它的声明必须集中放在 .h 文件中。

--------------------------------------------------------------------------------
原因：

    1. 提高可维护性
       修改接口时只需改一处。

    2. 提高可读性
       使用者可以在头文件看到完整接口。

    3. 避免重复声明导致的不一致。

--------------------------------------------------------------------------------
核心思想：

    接口应当唯一来源。
================================================================================
*/

// 模拟 bar.h
void bar();

// 模拟 bar.cpp
void bar() {
    std::cout << "bar\n";
}

// 模拟 foo.cpp
void foo() {
    bar();
}

int main() {
    foo();
    return 0;
}
