/*
================================================================================
C++ Core Guidelines — SF.5

每个 .cpp 文件必须包含定义其接口的头文件

--------------------------------------------------------------------------------
原则说明：

    一个实现文件（.cpp）如果实现了某个接口，
    必须包含声明该接口的头文件。

    不要在 .cpp 中“自己写一份声明”。

--------------------------------------------------------------------------------
原因：

    1. 让编译器尽早检查接口一致性
    2. 防止声明与定义不匹配
    3. 避免错误延迟到链接阶段才暴露

--------------------------------------------------------------------------------
核心思想：

    接口必须由头文件统一声明，
    实现文件必须包含该头文件进行一致性校验。
================================================================================
*/

#include <iostream>

/*
模拟 foo.h
*/
void foo(int);
int bar(long);
int foobar(int);

/*
模拟 foo.cpp
*/
void foo(int) { }

int bar(long) { return 1; }

// double foobar(int) { return 3.14; }  // ❌ 如果改成 double 会立即报错

int foobar(int) { return 42; }

int main()
{
    std::cout << foo << "\n";  // 只是为了避免未使用警告
    std::cout << bar(10L) << "\n";
    std::cout << foobar(5) << "\n";

    return 0;
}
