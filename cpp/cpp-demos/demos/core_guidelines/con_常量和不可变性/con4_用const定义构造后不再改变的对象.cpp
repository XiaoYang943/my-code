/*
================================================================================
C++ Core Guidelines — Con.4

用 const 定义构造后不再改变的对象

--------------------------------------------------------------------------------
原则说明：

    如果一个对象在构造完成后不会再改变，
    应当声明为 const。

--------------------------------------------------------------------------------
原因：

    1. 防止对象被意外修改
    2. 提高代码可推理性
    3. 编译器可以捕获误修改
    4. 更清晰表达设计意图

--------------------------------------------------------------------------------
核心思想：

    构造完成即确定的值，应当固定下来。
================================================================================
*/

#include <iostream>

int main()
{
    std::cout << "===== 非 const 示例 =====\n";

    int x = 7;  // ❌ 实际不会修改，却不是 const

    for (int i = 0; i < 3; ++i) {
        std::cout << x << " ";
    }

    std::cout << "\n";

    // 阅读代码时必须假设：
    // x 可能在循环中被修改


    std::cout << "\n===== const 示例 =====\n";

    const int y = 9;  // ✅ 构造后不再改变

    for (int i = 0; i < 3; ++i) {
        std::cout << y << " ";
    }

    std::cout << "\n";

    // y = 10;  // ❌ 编译错误


    std::cout << "\n===== 更真实的工程示例 =====\n";

    const double pi = 3.1415926;  // 常量应声明为 const

    double area = pi * 2 * 2;
    std::cout << "Area: " << area << "\n";

    return 0;
}