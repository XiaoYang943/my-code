/*
================================================================================
C++ Core Guidelines — Con.1

默认让对象不可变

--------------------------------------------------------------------------------
原则说明：

    如果一个对象不需要被修改，就应声明为 const。

    只有在确实需要修改时，才去掉 const。

--------------------------------------------------------------------------------
原因：

    1. 常量更容易推理
       不会发生意外修改。

    2. 防止无意或隐蔽的状态变化。

    3. 编译器可以帮助检查错误。

--------------------------------------------------------------------------------
核心思想：

    能不变，就不要变。
================================================================================
*/

#include <iostream>
#include <vector>

int main()
{
    std::vector<int> c{1, 2, 3};

    std::cout << "===== 正确示例：只读循环 =====\n";

    for (const int i : c) {   // ✅ 只读，使用 const
        std::cout << i << " ";
    }
    std::cout << "\n";


    std::cout << "\n===== 不推荐写法 =====\n";

    for (int i : c) {         // ❌ 实际没有修改，却没加 const
        std::cout << i << " ";
    }
    std::cout << "\n";


    std::cout << "\n===== 局部变量示例 =====\n";

    const int x = 10;
    std::cout << x << "\n";

    // x = 20;  // ❌ 编译错误


    std::cout << "\n===== 需要可变的情况 =====\n";

    int counter = 0;  // 需要修改
    counter++;
    std::cout << counter << "\n";


    return 0;
}